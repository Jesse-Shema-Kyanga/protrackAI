//  GET /api/reports/hr-pdf  (HR Workforce PDF)
// ════════════════════════════════════════════════════════════════════════════
router.get('/hr-pdf', async (req, res) => {
  try {
    const { period = 'month', reportType = 'all', viewMode = 'dept' } = req.query;
    if (req.user.role !== 'hr') return res.status(403).json({ error: 'HR access required' });

    const hrUser = await User.findOne({ id: req.user.id });
    const now = new Date();
    let endDate = new Date();
    let startDate = new Date();
    if (period === 'custom' && req.query.start && req.query.end) {
      startDate = new Date(req.query.start);
      endDate.setTime(new Date(req.query.end).setHours(23, 59, 59, 999));
    } else if (period === 'week') {
      startDate.setDate(now.getDate() - 7);
    } else if (period === 'month') {
      startDate.setTime(now.getTime() - 30 * 24 * 60 * 60 * 1000);
    } else {
      startDate.setHours(0, 0, 0, 0); // 'today'
    }

    const users = await User.find({ role: 'employee' }).select('id name dept team');
    const userIds = users.map(u => u.id);
    const activities = await Activity.find({ userId: { $in: userIds }, timestamp: { $gte: startDate, $lte: endDate } });
    const logs = await TimeLog.find({ userId: { $in: userIds }, timestamp: { $gte: startDate, $lte: endDate }, type: 'check-in' });

    const doc = new PDFDocument({ margin: 0, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    const hrDateStr = now.toISOString().split('T')[0];
    res.setHeader('Content-Disposition', `attachment; filename=MTN_Workforce_Audit_${viewMode.toUpperCase()}_${period}_${reportType}_${hrDateStr}.pdf`);
    doc.pipe(res);

    const titlePrefix = reportType === 'attendance' ? 'ATTENDANCE' : reportType === 'productivity' ? 'PRODUCTIVITY' : reportType === 'violation' ? 'VIOLATIONS' : 'WORKFORCE';
    let periodStr = period.toUpperCase();
    if (period === 'custom') {
      periodStr = `CUSTOM (${startDate.toISOString().split('T')[0]} to ${endDate.toISOString().split('T')[0]})`;
    }
    await drawCover(doc, `${titlePrefix} CAPACITY AUDIT`, `Organization-Wide ${viewMode === 'team' ? 'Team' : 'Departmental'} Analysis`, `Period: ${periodStr}`);

    let y = 110;

    // Organizational Overview
    const orgProd = activities.length > 0 ? Math.round((activities.filter(a => a.classified === 'productive').reduce((s,a) => s + a.duration, 0) / activities.reduce((s,a) => s + a.duration, 0)) * 100) : 0;
    const orgAtt = logs.length > 0 ? Math.round((logs.filter(l => l.status === 'present').length / logs.length) * 100) : 0;

    y = drawSectionHeader(doc, 'Global Performance Summary', y);
    y = drawSummaryHeader(doc, [
        { label: 'Total Staff', value: String(users.length) },
        { label: 'Avg Efficiency', value: orgProd + '%' },
        { label: 'Reliability', value: orgAtt + '%' },
        { label: 'Status', value: 'OPERATIONAL' }
    ], y);

    // Grouping Logic
    const groups = [...new Set(users.map(u => viewMode === 'team' ? u.team : u.dept).filter(Boolean))];
    const groupStats = groups.map((gName, i) => {
        const gUsers = users.filter(u => (viewMode === 'team' ? u.team : u.dept) === gName);
        const gIds = gUsers.map(u => u.id);
        const gActs = activities.filter(a => gIds.includes(a.userId));
        const gLogs = logs.filter(l => gIds.includes(l.userId));

        const tot = gActs.reduce((s,a) => s + (a.duration || 0), 0);
        const prd = gActs.filter(a => a.classified === 'productive').reduce((s,a) => s + (a.duration || 0), 0);
        const eff = tot > 0 ? Math.round((prd / tot) * 100) : 0;
        const att = gLogs.length > 0 ? Math.round((gLogs.filter(l => l.status === 'present').length / gLogs.length) * 100) : 0;

        if (reportType === 'attendance') {
            const lateCount = gLogs.filter(l => l.status === 'late').length;
            return [
                '#' + (i + 1),
                gName,
                att + '%',
                String(lateCount),
                { text: att >= 80 ? 'EXCELLENT' : 'REVIEW', color: att >= 80 ? GREEN : AMBER }
            ];
        } else if (reportType === 'productivity') {
            const focusHours = Math.round(prd / 3600);
            return [
                '#' + (i + 1),
                gName,
                eff + '%',
                formatDuration(prd),
                { text: eff >= 70 ? 'OPTIMAL' : 'RISK', color: eff >= 70 ? GREEN : RED }
            ];
        } else {
            return [
                '#' + (i + 1),
                gName,
                { text: eff + '%', color: eff >= 70 ? GREEN : AMBER, bold: true },
                att + '%',
                String(gIds.length)
            ];
        }
    });

    const headers = reportType === 'attendance' 
        ? ['SN', `${viewMode === 'team' ? 'Team' : 'Dept'} Name`, 'Attendance %', 'Late Count', 'Reliability Rank']
        : reportType === 'productivity'
        ? ['SN', `${viewMode === 'team' ? 'Team' : 'Dept'} Name`, 'Productivity %', 'Focus Time', 'Performance Rank']
        : ['SN', `${viewMode === 'team' ? 'Team' : 'Dept'} Name`, 'Productivity %', 'Attendance %', 'Headcount'];

    y = drawSectionHeader(doc, `${viewMode === 'team' ? 'Team' : 'Departmental'} Benchmarking`, y);
    y = drawTable(doc, headers, groupStats, { colW: [0, 30, 210, 320, 430] }, y);

    drawFooter(doc, now.toLocaleString());
    drawSignaturePage(doc, hrUser?.name || 'HR Administrator', now);
    doc.end();

  } catch (err) {
    console.error('HR PDF error:', err);
    res.status(500).json({ error: err.message });
  }
});

