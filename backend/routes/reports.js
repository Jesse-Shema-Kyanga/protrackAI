//  GET /api/reports  (JSON stats)
// ════════════════════════════════════════════════════════════════════════════
router.get('/', async (req, res) => {
  console.log(`[API] GET /api/reports - User: ${req.query.userId}, Period: ${req.query.period}`);
  try {
    const { userId, period = 'month', start, end } = req.query;
    if (!userId) return res.status(400).json({ error: 'Missing userId param' });

    const now = new Date();
    let startDate = new Date(now), endDate = new Date();

    if (period === 'custom' && start && end) {
      startDate = new Date(start);
      endDate = new Date(end);
    } else {
      if (period === 'today') startDate.setHours(0, 0, 0, 0);
      else if (period === 'week') startDate.setDate(now.getDate() - 7);
      else if (period === 'quarter') startDate.setMonth(now.getMonth() - 3);
      else if (period === 'month') startDate.setMonth(now.getMonth() - 1);
    }

    const activityMatch = { userId: new RegExp(`^${userId}$`, 'i'), timestamp: { $gte: startDate, $lte: endDate } };

    const stats = await Activity.aggregate([
      { $match: activityMatch },
      { $group: { _id: '$classified', totalDuration: { $sum: '$duration' } } }
    ]);

    const totalTime = stats.reduce((s, a) => s + (a.totalDuration || 0), 0);
    const productiveTime = stats.find(a => a._id === 'productive')?.totalDuration || 0;
    const neutralTime = stats.find(a => ['neutral', 'unknown', 'review_required'].includes(a._id))?.totalDuration || 0;
    const nonProductiveTime = stats.find(a => a._id === 'non-productive')?.totalDuration || 0;
    const efficiency = totalTime > 0 ? Math.round((productiveTime / totalTime) * 100) + '%' : '0%';

    const domainAgg = await Activity.aggregate([
      { $match: activityMatch },
      { $group: { _id: '$appName', duration: { $sum: '$duration' }, classified: { $first: '$classified' } } },
      { $sort: { duration: -1 } },
      { $limit: 15 }
    ]);

    const recentItems = await Activity.find(activityMatch).sort({ timestamp: -1 }).limit(100);
    const sanitized = sanitizeActivities(recentItems, 'employee');

    console.log(`[API] GET /api/reports - Success. Efficiency: ${efficiency}, Recent: ${sanitized.length}`);
    res.json({
      efficiency, totalTime, productiveTime, neutralTime, nonProductiveTime,
      recentActivities: sanitized,
      domainBreakdown: domainAgg.map(d => ({ name: d._id || 'Unknown', duration: d.duration, classified: d.classified })),
      period: { start: startDate, end: endDate }
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ════════════════════════════════════════════════════════════════════════════
//  GET /api/reports/pdf  (Employee PDF)
// ════════════════════════════════════════════════════════════════════════════
router.get('/pdf', async (req, res) => {
  try {
    const { userId, period = 'month', reportType = 'all' } = req.query;
    if (!userId) return res.status(400).json({ error: 'Missing userId param' });

    const user = await User.findOne({ id: userId });
    if (!user) return res.status(404).json({ error: 'User not found' });

    const requester = await User.findOne({ id: req.user.id });
    const requesterName = requester ? requester.name : (req.user.name || 'Authorized Personnel');

    const now = new Date();
    const endDate = new Date();
    let startDate;
    if (req.query.start && req.query.end) {
      startDate = new Date(req.query.start);
      endDate.setTime(new Date(req.query.end).setHours(23, 59, 59, 999));
    } else if (period === 'week') {
      startDate = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
    } else if (period === 'month') {
      startDate = new Date(now.getTime() - 30 * 24 * 60 * 60 * 1000);
    } else {
      startDate = new Date(now); startDate.setHours(0, 0, 0, 0);
    }

    const activities = await Activity.find({ userId, timestamp: { $gte: startDate, $lte: endDate } }).sort({ timestamp: -1 });
    const timeLogs   = await TimeLog.find({ userId, timestamp: { $gte: startDate, $lte: endDate } });
    
    // Header for PDF
    const doc = new PDFDocument({ margin: 0, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=Audit_${user.name.replace(/\s+/g, '_')}_${period}_${reportType}.pdf`);
    doc.pipe(res);

    const title = reportType === 'violation' ? 'POLICY VIOLATIONS RECORD' : reportType.toUpperCase() + ' PERFORMANCE RECORD';
    let periodStr = period.toUpperCase();
    if (period === 'custom') {
      periodStr = `CUSTOM (${startDate.toISOString().split('T')[0]} to ${endDate.toISOString().split('T')[0]})`;
    }
    await drawCover(doc, title, `Employee: ${user.name} (${userId})`, `Period: ${periodStr} Audit Document`);

    let y = 110;

    // ──────────────────────────────────────────────────────────────────────────
    // ATTENDANCE REALM
    // ──────────────────────────────────────────────────────────────────────────
    if (reportType === 'all' || reportType === 'attendance') {
        const checkIns = timeLogs.filter(l => l.type === 'check-in');
        const present = checkIns.filter(l => l.status === 'present').length;
        const lates = checkIns.filter(l => l.status === 'late').length;

        y = drawSectionHeader(doc, 'Attendance Audit Summary', y);
        y = drawSummaryHeader(doc, [
            { label: 'Total Logs', value: String(checkIns.length) },
            { label: 'On-Time', value: String(present) },
            { label: 'Late Flags', value: String(lates) },
            { label: 'Reliability', value: (checkIns.length > 0 ? Math.round((present / checkIns.length) * 100) : 0) + '%' }
        ], y);

        const auditRows = await Promise.all(checkIns.map(async (l, i) => {
            const dayStart = new Date(l.timestamp); dayStart.setHours(0,0,0,0);
            const dayEnd = new Date(l.timestamp); dayEnd.setHours(23,59,59,999);
            const firstTask = await Activity.findOne({ userId, timestamp: { $gte: dayStart, $lte: dayEnd } }).sort({ timestamp: 1 });
            const gap = firstTask ? Math.round((firstTask.timestamp - l.timestamp) / 60000) : 0;
            return [
                '#' + (i + 1),
                l.timestamp.toLocaleDateString('en-GB'),
                l.timestamp.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
                firstTask ? firstTask.timestamp.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : '—',
                gap > 0 ? gap + 'm' : '—',
                { text: (l.status || 'present').toUpperCase(), color: l.status === 'late' ? AMBER : GREEN, bold: true }
            ];
        }));

        const maxRows = period === 'today' ? 1 : period === 'week' ? 7 : 31;
        y = drawTable(doc, 
            ['SN', 'Date', 'Clock In', 'First Task', 'Gap', 'Status'],
            auditRows.slice(0, maxRows), 
            { colW: [0, 30, 110, 200, 290, 380] },
            y
        );
    }

    // ──────────────────────────────────────────────────────────────────────────
    // VIOLATIONS REALM (Individual)
    // ──────────────────────────────────────────────────────────────────────────
    if (reportType === 'all' || reportType === 'violation') {
        const lateLogs = timeLogs.filter(l => l.type === 'check-in' && l.status === 'late');
        const totalDur = activities.reduce((s, a) => s + (a.duration || 0), 0);
        const prodDur = activities.filter(a => a.classified === 'productive').reduce((s, a) => s + (a.duration || 0), 0);
        const ratio = totalDur > 0 ? Math.round((prodDur / totalDur) * 100) : 0;
        
        if (reportType === 'violation' || lateLogs.length > 2 || ratio < 60) {
            y = drawSectionHeader(doc, 'Policy Violations & Warnings', y);
            
            const infractions = [];
            if (lateLogs.length > 2) infractions.push(`Chronic Tardiness: Arrived late ${lateLogs.length} times in this period.`);
            if (ratio > 0 && ratio < 60) infractions.push(`Low Productivity: Efficiency ratio is ${ratio}%. Well below the 70% minimum threshold.`);
            
            if (infractions.length === 0 && reportType === 'violation') {
                infractions.push('No obvious systemic violations detected in this period.');
            }

            y = drawSummaryHeader(doc, infractions.map((inf, idx) => ({ label: `Warning ${idx + 1}`, value: inf })), y);
            
            const nprdActivities = aggregateByDomain(activities.filter(a => a.classified === 'non-productive'));
            const violatorRows = nprdActivities.slice(0, 5).map((d, i) => [
                '#' + (i + 1),
                d.domain,
                'UNAUTHORIZED/DISTRACTION',
                formatDuration(d.totalDuration),
                Math.round(d.percent) + '%'
            ]);

            if (violatorRows.length > 0) {
                y = drawTable(doc,
                    ['SN', 'Non-Productive Domain', 'Flag Type', 'Time Lost', 'Share %'],
                    violatorRows,
                    { colW: [0, 30, 240, 350, 440] },
                    y
                );
            }
        }
    }

    // ──────────────────────────────────────────────────────────────────────────
    // PRODUCTIVITY REALM
    // ──────────────────────────────────────────────────────────────────────────
    if (reportType === 'all' || reportType === 'productivity') {
        const totalDur = activities.reduce((s, a) => s + (a.duration || 0), 0);
        const prodDur = activities.filter(a => a.classified === 'productive').reduce((s, a) => s + (a.duration || 0), 0);
        const ratio = totalDur > 0 ? Math.round((prodDur / totalDur) * 100) : 0;

        y = drawSectionHeader(doc, 'Productivity Alignment & Efficiency', y);
        y = drawSummaryHeader(doc, [
            { label: 'Total Logged', value: formatDuration(totalDur) },
            { label: 'Productive', value: formatDuration(prodDur) },
            { label: 'Efficiency', value: ratio + '%' },
            { label: 'Status', value: ratio >= 70 ? 'OPTIMAL' : 'RECOVERY' }
        ], y);

        const domainStats = aggregateByDomain(activities);
        const toolRows = domainStats.slice(0, 10).map((d, i) => [
            '#' + (i + 1),
            d.domain,
            { text: (d.classified || 'Neutral').toUpperCase(), color: d.classified === 'productive' ? GREEN : d.classified === 'non-productive' ? RED : LIGHT },
            formatDuration(d.totalDuration),
            Math.round(d.percent) + '%'
        ]);

        y = drawTable(doc,
            ['SN', 'Application / Domain', 'Classification', 'Focus Time', 'Share %'],
            toolRows,
            { colW: [0, 30, 240, 350, 440] },
            y
        );
    }

    drawFooter(doc, now.toLocaleString());
    drawSignaturePage(doc, requesterName, now);
    doc.end();

  } catch (err) {
    console.error('Individual PDF error:', err);
    res.status(500).json({ error: err.message });
  }
});

