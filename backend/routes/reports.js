const drawTable = (doc, headers, rows, config, y) => {
  const { colW, xStart = L, rowH = 18, fontSize = 7.5 } = config;
  
  // Header
  doc.rect(xStart, y, COL_W, rowH).fill('#222222');
  doc.fontSize(fontSize).font('Helvetica-Bold').fillColor(GOLD);
  headers.forEach((h, i) => {
    doc.text(h.toUpperCase(), xStart + colW[i] + 4, y + 5, { lineBreak: false });
  });
  y += rowH + 2;

  // Rows
  rows.forEach((row, ri) => {
    if (ri % 2 === 1) doc.rect(xStart, y - 1, COL_W, rowH).fill('#F9F9F9');
    doc.fontSize(fontSize).font('Helvetica').fillColor('#333333');
    
    row.forEach((cell, ci) => {
      // Handle colors if cell is an object
      const val = typeof cell === 'object' ? cell.text : cell;
      const color = typeof cell === 'object' ? cell.color : '#333333';
      const isBold = typeof cell === 'object' ? cell.bold : false;

      doc.fillColor(color).font(isBold ? 'Helvetica-Bold' : (ci === 0 ? 'Helvetica-Bold' : 'Helvetica'))
         .text(val, xStart + colW[ci] + 4, y + 4, { lineBreak: false });
    });
    y += rowH;
  });
  
  return y + 10;
};

const drawSummaryHeader = (doc, data, y) => {
    doc.rect(L, y, COL_W, 28).fill(DARK);
    doc.rect(L, y, 3, 28).fill(GOLD);
    
    const count = data.length;
    const unitW = COL_W / count;
    
    data.forEach((item, i) => {
        doc.fontSize(6).font('Helvetica-Bold').fillColor(LIGHT).text(item.label.toUpperCase(), L + (i * unitW) + 10, y + 6, { lineBreak: false });
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#FFFFFF').text(item.value, L + (i * unitW) + 10, y + 14, { lineBreak: false });
    });
    return y + 36;
};

